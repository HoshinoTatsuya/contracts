/**
 * Режим сверки двух снимков.
 *
 * - `compatible` — стороны на РАЗНЫХ версиях (раздельная выкатка): писатель
 *   вправе добавлять необязательное, читатель — читать терпимо. Нарушение —
 *   только то, что читатель отвергнет или поймёт неверно;
 * - `aligned` — стороны обязаны быть на одной версии, но направление важно:
 *   читатель вправе быть мягче писателя, не строже, и наборы полей обязаны
 *   совпасть (кладут то, чего не читают, или читают то, чего не кладут, —
 *   нарушение);
 * - `mirror` — две копии одного контракта обязаны совпадать по форме целиком.
 */
export type CompareMode = 'compatible' | 'aligned' | 'mirror';
