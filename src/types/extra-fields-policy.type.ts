/**
 * Поля вне формы при ЗАПИСИ:
 *
 * - `refused` — `write()` отвергает payload с ними (`defineContract`, по
 *   умолчанию): на провод уходит только описанное формой;
 * - `kept` — `write()` их пропускает (`unknownFields: 'keep'`): сторона
 *   пересылает то, что получила, и на проводе может оказаться что угодно;
 * - `unchecked` — их никто не проверяет (контракт снят с типа TypeScript:
 *   структурная типизация допускает лишние свойства).
 */
export type ExtraFieldsPolicy = 'refused' | 'kept' | 'unchecked';
