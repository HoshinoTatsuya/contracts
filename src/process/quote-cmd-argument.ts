import { ContractDefinitionError } from '../errors/contract-definition.error';

/**
 * Аргумент для строки `cmd.exe /d /s /c "…"`, которой запускается обёртка
 * `node_modules/.bin/<имя>.cmd`. Кавычки сами по себе cmd.exe не защищают:
 * `%VAR%` раскрывается и внутри них, `&`/`|` за парой кавычек режут команду.
 * Поэтому: сначала правила разбора argv программой (обратные слэши перед
 * кавычкой удваиваются, кавычка — `\"`, хвостовые обратные слэши удваиваются),
 * затем кавычки вокруг, затем `^` перед КАЖДЫМ метасимволом, включая сами
 * кавычки, — cmd.exe ни разу не входит в режим кавычек и снимает каждый `^`.
 * Обёртка `.cmd` передаёт аргументы дальше через `%*`, и cmd.exe разбирает
 * строку второй раз, — экранирование двойное. `%` после `^` не образует имени
 * переменной без `^`, а неопределённая переменная в командной строке остаётся
 * как есть: `%PATH%` доходит до программы буквально.
 *
 * Перевод строки в командной строке cmd.exe не выразить — отказ снимка.
 */
export function quoteCmdArgument(argument: string): string {
  if (/[\r\n\0]/.test(argument)) {
    throw new ContractDefinitionError(
      'снимок',
      argument,
      'путь с переводом строки не передать в cmd.exe — переименуйте',
    );
  }
  // Метасимволы cmd.exe: каждый экранируется `^`, иначе cmd разберёт его сам.
  const CMD_META = /([()\][%!^"`<>&|;, *?])/g;
  const msvcrt = argument.replace(/(\\*)"/g, '$1$1\\"').replace(/(\\*)$/, '$1$1');
  return `"${msvcrt}"`.replace(CMD_META, '^$1').replace(CMD_META, '^$1');
}
