import { quoteCmdArgument } from './quote-cmd-argument';

/**
 * Ожидаемые строки выведены руками из правил cmd.exe (фаза 2 снимает `^` вне
 * кавычек) и MSVCRT (обратные слэши перед кавычкой удваиваются): обёртка `.cmd`
 * разбирает строку дважды, поэтому каждый `^`/метасимвол экранирован дважды.
 * Что строки действительно доходят до программы буквально, проверяет модель
 * cmd.exe в спеке `buildCmdInvocation`.
 */
describe('quoteCmdArgument: аргумент для cmd.exe /d /s /c и обёртки .cmd', () => {
  it.each([
    ['plain', '^^^"plain^^^"'],
    ['a b', '^^^"a^^^ b^^^"'],
    // %VAR% раскрылся бы и в кавычках: `^` разрывает имя переменной.
    ['%PATH%', '^^^"^^^%PATH^^^%^^^"'],
    ['!x!', '^^^"^^^!x^^^!^^^"'],
    ['a&b|c', '^^^"a^^^&b^^^|c^^^"'],
    ['x^y', '^^^"x^^^^y^^^"'],
    // Кавычка внутри: обратные слэши перед ней удваиваются, сама — \".
    ['say "hi"', '^^^"say^^^ \\^^^"hi\\^^^"^^^"'],
    // Хвостовые обратные слэши удваиваются: иначе экранировали бы закрывающую кавычку.
    ['dir\\', '^^^"dir\\\\^^^"'],
    ['', '^^^"^^^"'],
  ])('%j → %s', (arg, quoted) => {
    expect(quoteCmdArgument(arg)).toBe(quoted);
  });

  it('перевод строки и NUL в командной строке cmd.exe не выразить — отказ', () => {
    expect(() => quoteCmdArgument('a\nb')).toThrow(/перевод/);
    expect(() => quoteCmdArgument('a\rb')).toThrow(/перевод/);
    expect(() => quoteCmdArgument('a\0b')).toThrow(/перевод/);
  });
});
